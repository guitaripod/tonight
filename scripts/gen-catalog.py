def table(name, doc, items):
    rows = "\n".join(f'    ({i}, "{n}"),' for i, n in sorted(items))
    return f"/// {doc}\nstatic {name}: &[(u32, &str)] = &[\n{rows}\n];\n"


def main():
    req = urllib.request.Request(
        "https://store.steampowered.com/tagdata/populartags/english",
        headers={"User-Agent": "Mozilla/5.0"},
    )
    tags = [(t["tagid"], t["name"]) for t in json.load(urllib.request.urlopen(req, timeout=30))]
    assert len(tags) > 300, "tag list looks truncated"
    out = [
        "//! Generated by scripts/gen-catalog.py. Do not edit by hand.\n",
        table("TAGS", "Store tag ids, sorted for binary search.", tags),
        table("CATEGORIES", "Store category ids, sorted for binary search.", CATEGORIES.items()),
        table("GENRES", "Store genre ids, sorted for binary search.", GENRES.items()),
        """fn lookup(table: &'static [(u32, &'static str)], id: u32) -> Option<&'static str> {
    table
        .binary_search_by_key(&id, |(k, _)| *k)
        .ok()
        .map(|i| table[i].1)
}

pub fn tag_name(id: u32) -> Option<&'static str> {
    lookup(TAGS, id)
}

pub fn category_name(id: u32) -> Option<&'static str> {
    lookup(CATEGORIES, id)
}

pub fn genre_name(id: u32) -> Option<&'static str> {
    lookup(GENRES, id)
}
""",
    ]
    sys.stdout.write("\n".join(out))


main()
